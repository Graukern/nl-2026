# Слайд 10. Операции и строки

println("10 ÷ 3 = ", 10 ÷ 3)      # целочисленное деление
println("10 / 3 = ", 10 / 3)      # вещественное деление
println("2^10 = ", 2^10)
println("17 % 5 = ", 17 % 5)

println("10 == 10 -> ", 10 == 10)
println("10 != 5  -> ", 10 != 5)
println("10 > 5   -> ", 10 > 5)
println("true && false -> ", true && false)
println("true || false -> ", true || false)
println("!true -> ", !true)

println("Hello " * "Julia")
println("Julia"^3)
name = "Julia"
println("Hello, $name!")
