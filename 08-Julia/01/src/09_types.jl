# Слайд 9. Типы данных и переменные

x = 42
y = 3.14
name = "Julia"
flag = true
ch = 'J'

println("x = ", x, ", type = ", typeof(x))
println("y = ", y, ", type = ", typeof(y))
println("name = ", name, ", type = ", typeof(name))
println("flag = ", flag, ", type = ", typeof(flag))
println("ch = ", ch, ", type = ", typeof(ch))

# Переменная в Julia — имя, связанное со значением.
value = 10
println("value = ", value, ", type = ", typeof(value))
value = "ten"
println("value = ", value, ", type = ", typeof(value))
